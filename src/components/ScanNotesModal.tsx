import React, { useState } from 'react';
import { SmartNote } from '../types';

interface ScanNotesModalProps {
  isOpen: boolean;
  onClose: () => void;
  onNoteCreated: (note: SmartNote) => void;
}

export const ScanNotesModal: React.FC<ScanNotesModalProps> = ({
  isOpen,
  onClose,
  onNoteCreated,
}) => {
  const [subject, setSubject] = useState('Organic Chemistry II');
  const [title, setTitle] = useState('');
  const [rawText, setRawText] = useState('');
  const [isProcessing, setIsProcessing] = useState(false);
  const [analyzedNote, setAnalyzedNote] = useState<SmartNote | null>(null);

  if (!isOpen) return null;

  const presets = [
    {
      label: 'Stereochemistry & Enantiomers',
      subject: 'Organic Chemistry II',
      title: 'Chirality & CIP (R/S) Priority Rules',
      text: 'Chiral centers have 4 distinct groups. Priority based on atomic number: -I > -Br > -Cl > -OH > -CH3 > -H. Lowest priority 4 points into page. Clockwise is R, counterclockwise is S. Meso compounds have stereocenters but an internal mirror plane making them achiral.',
    },
    {
      label: 'ATP Synthase & Proton Motive Force',
      subject: 'Cellular Biology',
      title: 'Chemiosmotic Coupling & Rotor Mechanics',
      text: 'Proton pumping across the inner mitochondrial membrane creates a pH and electrical gradient. Protons return through the F0 c-ring channel, turning the central gamma stalk. The F1 catalytic head alternates through open, loose, and tight conformations to synthesize ATP from ADP and inorganic phosphate.',
    },
    {
      label: 'Rotational Torque & Angular Momentum',
      subject: 'Physics & Dynamics',
      title: 'Torque, Moment of Inertia & Conservation',
      text: 'Torque is the rotational equivalent of force, tau = r x F = I * alpha. In the absence of external torque, angular momentum L = I * omega is strictly conserved. A spinning figure skater pulls in arms, decreasing I and increasing omega.',
    },
  ];

  const handleApplyPreset = (p: typeof presets[0]) => {
    setSubject(p.subject);
    setTitle(p.title);
    setRawText(p.text);
  };

  const handleAnalyze = async () => {
    if (!rawText.trim()) return;
    setIsProcessing(true);

    try {
      const res = await fetch('/api/ai/notes', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          rawText,
          subject,
        }),
      });

      const data = await res.json();
      const newNote: SmartNote = {
        id: `note-${Date.now()}`,
        title: title.trim() || `${subject} Core Concepts`,
        subject,
        courseCode: subject.includes('Organic') ? 'CHEM 240' : subject.includes('Physics') ? 'PHYS 201' : 'BIO 110',
        date: 'Just now',
        summary: data.summary || 'Summary generated by SmartStudy AI.',
        keyTakeaways: data.keyTakeaways || ['Core principle extracted from notes.'],
        examTrap: data.examTrap || 'Pay close attention to sign conventions and units.',
        flashcards: data.flashcards || [{ front: 'Core concept', back: 'Summary explanation' }],
        cues: ['Key Term', 'Mechanism', 'Critical Trap'],
      };

      setAnalyzedNote(newNote);
      onNoteCreated(newNote);
    } catch (err) {
      console.error('Failed to analyze notes:', err);
    } finally {
      setIsProcessing(false);
    }
  };

  const handleReset = () => {
    setAnalyzedNote(null);
    setTitle('');
    setRawText('');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-surface-container-lowest w-full max-w-lg rounded-2xl shadow-2xl overflow-hidden border border-surface-container flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="px-5 py-4 border-b border-surface-container flex items-center justify-between bg-surface-container-low">
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-secondary-container/30 text-secondary flex items-center justify-center">
              <span className="material-symbols-outlined text-[20px]">document_scanner</span>
            </div>
            <div>
              <h3 className="font-headline font-bold text-base text-on-surface">
                AI Note Scanner &amp; Ingestion
              </h3>
              <p className="text-xs text-on-surface-variant">
                Convert raw lecture notes into Cornell study guides &amp; flashcards
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 rounded-full flex items-center justify-center text-on-surface-variant hover:bg-surface-container transition-colors"
          >
            <span className="material-symbols-outlined text-[20px]">close</span>
          </button>
        </div>

        {/* Content */}
        <div className="p-5 overflow-y-auto flex-1 space-y-4">
          {!analyzedNote ? (
            <>
              {/* Preset quick buttons */}
              <div>
                <label className="text-xs font-headline font-semibold text-on-surface-variant block mb-1.5">
                  Try Sample Lecture Notes
                </label>
                <div className="flex flex-wrap gap-1.5">
                  {presets.map((p, idx) => (
                    <button
                      key={idx}
                      onClick={() => handleApplyPreset(p)}
                      className="text-xs px-2.5 py-1 rounded-lg bg-surface-container hover:bg-surface-container-high text-on-surface transition-colors active:scale-95"
                    >
                      {p.label}
                    </button>
                  ))}
                </div>
              </div>

              {/* Subject selector */}
              <div>
                <label className="text-xs font-headline font-semibold text-on-surface-variant block mb-1">
                  Subject / Course
                </label>
                <select
                  value={subject}
                  onChange={(e) => setSubject(e.target.value)}
                  className="w-full text-xs font-headline p-2.5 rounded-xl border border-surface-container bg-surface-container-low text-on-surface focus:outline-none focus:ring-2 focus:ring-primary"
                >
                  <option value="Organic Chemistry II">CHEM 240: Organic Chemistry II</option>
                  <option value="Physics & Dynamics">PHYS 201: Physics &amp; Dynamics</option>
                  <option value="Cellular Biology">BIO 110: Cellular Biology</option>
                  <option value="Macroeconomics">ECON 102: Macroeconomics</option>
                </select>
              </div>

              {/* Title input */}
              <div>
                <label className="text-xs font-headline font-semibold text-on-surface-variant block mb-1">
                  Note Title
                </label>
                <input
                  type="text"
                  placeholder="e.g., Alkene Reactions & Electrophilic Additions"
                  value={title}
                  onChange={(e) => setTitle(e.target.value)}
                  className="w-full text-xs p-2.5 rounded-xl border border-surface-container bg-surface-container-low text-on-surface focus:outline-none focus:ring-2 focus:ring-primary"
                />
              </div>

              {/* Text / Notes Input */}
              <div>
                <div className="flex items-center justify-between mb-1">
                  <label className="text-xs font-headline font-semibold text-on-surface-variant">
                    Lecture Notes / Transcribed Text
                  </label>
                  <span className="text-[10px] text-on-surface-variant">Supports copy-paste or transcript</span>
                </div>
                <textarea
                  rows={5}
                  placeholder="Paste lecture notes, equations, textbook excerpt, or type key points here..."
                  value={rawText}
                  onChange={(e) => setRawText(e.target.value)}
                  className="w-full text-xs p-3 rounded-xl border border-surface-container bg-surface-container-low text-on-surface focus:outline-none focus:ring-2 focus:ring-primary leading-relaxed font-sans"
                />
              </div>
            </>
          ) : (
            <div className="space-y-4 animate-in fade-in duration-200">
              <div className="p-3.5 rounded-xl bg-secondary-fixed/30 border border-secondary/20 flex items-center gap-3">
                <span className="material-symbols-outlined text-secondary text-[24px]">verified</span>
                <div>
                  <h4 className="font-headline font-bold text-sm text-on-secondary-fixed">
                    Smart Study Guide Generated!
                  </h4>
                  <p className="text-[11px] text-on-secondary-fixed-variant">
                    Added to your Smart Notes library with {analyzedNote.flashcards.length} automatic flashcards.
                  </p>
                </div>
              </div>

              <div className="border border-surface-container rounded-xl p-4 bg-surface-container-low space-y-3">
                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-primary font-headline">
                    Summary Breakdown
                  </span>
                  <p className="text-xs text-on-surface mt-1 leading-relaxed">
                    {analyzedNote.summary}
                  </p>
                </div>

                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-secondary font-headline">
                    Key Principles
                  </span>
                  <ul className="mt-1 space-y-1 text-xs text-on-surface-variant list-disc list-inside">
                    {analyzedNote.keyTakeaways.map((takeaway, i) => (
                      <li key={i}>{takeaway}</li>
                    ))}
                  </ul>
                </div>

                <div className="p-2.5 rounded-lg bg-error-container/40 border border-error/20">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-error font-headline flex items-center gap-1">
                    <span className="material-symbols-outlined text-[14px]">warning</span>
                    Exam Trap Alert
                  </span>
                  <p className="text-xs text-on-error-container mt-0.5">
                    {analyzedNote.examTrap}
                  </p>
                </div>
              </div>
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="px-5 py-3 border-t border-surface-container bg-surface-container-low flex items-center justify-between">
          {!analyzedNote ? (
            <>
              <button
                onClick={onClose}
                className="px-4 py-2 text-xs font-headline font-semibold text-on-surface-variant hover:text-on-surface"
              >
                Cancel
              </button>
              <button
                onClick={handleAnalyze}
                disabled={!rawText.trim() || isProcessing}
                className={`px-5 py-2 rounded-xl font-headline text-xs font-semibold flex items-center gap-1.5 transition-all ${
                  rawText.trim() && !isProcessing
                    ? 'bg-primary text-on-primary hover:bg-primary-container active:scale-95 shadow-xs'
                    : 'bg-surface-variant text-on-surface-variant/50 cursor-not-allowed'
                }`}
              >
                {isProcessing ? (
                  <>
                    <span className="w-3.5 h-3.5 border-2 border-white border-t-transparent rounded-full animate-spin"></span>
                    <span>Processing with Gemini...</span>
                  </>
                ) : (
                  <>
                    <span className="material-symbols-outlined text-[16px]">auto_awesome</span>
                    <span>Generate Smart Notes</span>
                  </>
                )}
              </button>
            </>
          ) : (
            <>
              <button
                onClick={handleReset}
                className="px-4 py-2 text-xs font-headline font-semibold text-on-surface-variant hover:text-on-surface"
              >
                Scan Another Note
              </button>
              <button
                onClick={onClose}
                className="px-5 py-2 rounded-xl bg-primary text-on-primary font-headline text-xs font-semibold hover:bg-primary-container active:scale-95"
              >
                Done
              </button>
            </>
          )}
        </div>
      </div>
    </div>
  );
};
